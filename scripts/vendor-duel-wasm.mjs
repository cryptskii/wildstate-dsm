// Vendors the staked-match program (DSM `crates/wildstate-duel-wasm`, built with
// `wasm-pack build --target nodejs`) into src/vendor/wildstate-duel/.
//
// The game server runs as the vite dev server, as vite's server build and as one esbuild bundle
// (deploy/game/Dockerfile copies only that file), so the program cannot be a .wasm file read from
// beside its glue. The glue is rewritten as an ES module whose WebAssembly bytes are embedded
// (wasm-bytes.js, Base64), and the .wasm itself is kept beside it so a test can hold the two
// equal and the program hash can be read from the bytes that run.
//
//   node scripts/vendor-duel-wasm.mjs <wasm-pack output dir> <DSM commit>
import { createHash } from 'node:crypto';
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const [pkg, commit] = process.argv.slice(2);
if (!pkg || !commit) throw new Error('usage: node scripts/vendor-duel-wasm.mjs <wasm-pack output dir> <DSM commit>');
const out = new URL('../src/vendor/wildstate-duel/', import.meta.url).pathname;
mkdirSync(out, { recursive: true });

const glue = readFileSync(join(pkg, 'wildstate_duel_wasm.js'), 'utf8');
const names = [];
const body = glue
  .split('\n')
  .filter((line) => {
    const m = line.match(/^exports\.(\w+) = \1;$/);
    if (m) names.push(m[1]);
    return !m;
  })
  .join('\n')
  .replace(
    "const wasmPath = `${__dirname}/wildstate_duel_wasm_bg.wasm`;\nconst wasmBytes = require('fs').readFileSync(wasmPath);",
    "const wasmBytes = Buffer.from(WASM_BASE64, 'base64');",
  )
  .replace('/* @ts-self-types="./wildstate_duel_wasm.d.ts" */\n', '');
if (/\brequire\(|__dirname|\bexports\./.test(body)) throw new Error('the glue has CommonJS left in it: the generator changed');
if (!names.length) throw new Error('the glue exports nothing: the generator changed');

const wasm = readFileSync(join(pkg, 'wildstate_duel_wasm_bg.wasm'));
const sha256 = createHash('sha256').update(wasm).digest('hex');
const header = `// Generated by scripts/vendor-duel-wasm.mjs from DSM ${commit} (crates/wildstate-duel-wasm). Do not edit.\n`;
writeFileSync(join(out, 'wildstate_duel_wasm.js'), `${header}import { WASM_BASE64 } from './wasm-bytes.js';\n\n${body.trimEnd()}\n\nexport { ${names.join(', ')} };\n`);
writeFileSync(join(out, 'wasm-bytes.js'), `${header}// The bytes of wildstate_duel_wasm_bg.wasm (sha256 ${sha256}).\nexport const WASM_BASE64 = '${wasm.toString('base64')}';\n`);
writeFileSync(join(out, 'wasm-bytes.d.ts'), `${header}export declare const WASM_BASE64: string;\n`);
copyFileSync(join(pkg, 'wildstate_duel_wasm.d.ts'), join(out, 'wildstate_duel_wasm.d.ts'));
copyFileSync(join(pkg, 'wildstate_duel_wasm_bg.wasm'), join(out, 'wildstate_duel_wasm_bg.wasm'));
writeFileSync(join(out, 'SOURCE'), `DSM commit ${commit}\ncrates/wildstate-duel-wasm, wasm-pack build --target nodejs --release --no-opt\nwildstate_duel_wasm_bg.wasm sha256 ${sha256}\n`);
console.log(`vendored ${names.length} exports, ${wasm.length} wasm bytes (sha256 ${sha256}) into ${out}`);
